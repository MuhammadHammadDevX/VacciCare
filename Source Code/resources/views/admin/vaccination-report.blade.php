<script>
function printReport(sectionId) {
    const validSections = ['childReport', 'dateReport', 'vaccineReport', 'all'];
    const target = validSections.includes(sectionId) ? sectionId : 'all';

    // Set attribute for print media query targeting
    document.body.setAttribute('data-print-target', target);

    // Update print header text dynamically
    const titleEl = document.getElementById('printHeaderTitle');
    const subtitleEl = document.getElementById('printHeaderSubtitle');
    const timeEl = document.getElementById('printHeaderTimestamp');

    if (timeEl) {
        const now = new Date();
        timeEl.textContent = now.toLocaleDateString('en-GB', { day: '2-digit', month: 'short', year: 'numeric' }) + ', ' +
                             now.toLocaleTimeString('en-US', { hour: '2-digit', minute: '2-digit', hour12: true });
    }

    if (titleEl && subtitleEl) {
        if (target === 'childReport') {
            titleEl.textContent = 'Child-wise Vaccination History Report';
            subtitleEl.textContent = 'Detailed log of child immunizations, parent details, vaccines, dates, and administering hospitals.';
        } else if (target === 'dateReport') {
            titleEl.textContent = 'Vaccination Date-wise Activity Report';
            subtitleEl.textContent = 'Daily immunization volumes, completed doses, pending bookings, and progress completion rates.';
        } else if (target === 'vaccineReport') {
            titleEl.textContent = 'Vaccine Usage & Hospital Stock Report';
            subtitleEl.textContent = 'Doses administered, accredited hospital stock availability, and distribution status.';
        } else {
            titleEl.textContent = 'Comprehensive Vaccination Management Report';
            subtitleEl.textContent = 'Consolidated audit records of child vaccinations, daily activity volumes, and hospital vaccine inventory.';
        }
    }

    // Invoke browser native print / PDF export
    window.print();
}

window.addEventListener('afterprint', function () {
    document.body.removeAttribute('data-print-target');
});

window.onafterprint = function () {
    document.body.removeAttribute('data-print-target');
};

document.addEventListener("DOMContentLoaded", function () {
    const reportTypeSelect = document.getElementById("reportType");
    const panels = document.querySelectorAll(".report-panel");

    if (reportTypeSelect) {
        reportTypeSelect.addEventListener("change", function () {
            const val = this.value;
            if (val === "all") {
                panels.forEach(p => p.style.display = "");
            } else if (val === "child") {
                panels.forEach(p => p.style.display = p.id === "childReport" ? "" : "none");
            } else if (val === "date") {
                panels.forEach(p => p.style.display = p.id === "dateReport" ? "" : "none");
            } else if (val === "vaccine") {
                panels.forEach(p => p.style.display = p.id === "vaccineReport" ? "" : "none");
            }
        });
    }
});
</script>
